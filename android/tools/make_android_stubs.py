#!/usr/bin/env python3
"""Writes build/native/stubs.cpp for the Android build: weak stand-ins for the retail functions the game refers to by their
retail labels (FUN_xxxxxxxx / func_xxxxxxxx: the disc's addresses) that nothing in the sources defines yet.

The desktop build makes these from the objects' undefined symbols (native/tools/make_stubs.py, with nm). The Android build
uses ndk-build, which links everything in one step, so the objects can't be read first. This makes the same stand-ins from
the labels' spelling instead: every label the sources and the generated data mention. A real definition (a RETAIL(label)
function, or an EABI_EXPORT) is a strong symbol with the same name, which takes the weak one's place at link time, so the
stand-in only does something where nothing defines the label. Like make_stubs.py, a stand-in logs its name the first time
it's called and returns 0.

Usage: make_android_stubs.py <repo root>
"""
import os
import re
import sys

ROOT = os.path.abspath(sys.argv[1])
OUT = os.path.join(ROOT, "build/native/stubs.cpp")

# The retail labels: the disc's functions (FUN_) and the functions the split names (func_), eight hex digits
LABEL = re.compile(r"\b(?:FUN|func)_[0-9A-Fa-f]{8}\b")

def scan(folder, suffixes):
    found = set()
    for dirpath, _, files in os.walk(folder):
        for name in files:
            if name.endswith(suffixes):
                with open(os.path.join(dirpath, name), encoding="utf-8", errors="ignore") as f:
                    found.update(LABEL.findall(f.read()))
    return found

labels = scan(os.path.join(ROOT, "src"), (".cpp", ".h")) | scan(os.path.join(ROOT, "include"), (".h", ".inc")) \
    | scan(os.path.join(ROOT, "build/native"), (".cpp", ".h"))
labels = sorted(labels)

lines = [
    "// Generated by android/tools/make_android_stubs.py: weak stand-ins for the retail labels nothing defines yet. Don't edit",
    '#include "native.h"',
    "",
    "#include <atomic>",
    "#include <cstdint>",
    "",
    "namespace",
    "{",
    "void Missing(std::atomic<bool>& said, const char* name)",
    "{",
    "    if (!said.exchange(true) && Native::GetSettings().logStubs)",
    "    {",
    '        Native::Log("not implemented yet: %s", name);',
    "    }",
    "}",
    "}",
    "",
    'extern "C"',
    "{",
]
for index, label in enumerate(labels):
    lines += [
        f'__attribute__((weak)) std::uintptr_t Stub{index}() asm("{label}");',
        f"std::uintptr_t Stub{index}()",
        "{",
        "    static std::atomic<bool> said;",
        f'    Missing(said, "{label}");',
        "    return 0;",
        "}",
    ]
lines.append("}")

os.makedirs(os.path.dirname(OUT), exist_ok=True)
with open(OUT, "w", encoding="utf-8") as f:
    f.write("\n".join(lines) + "\n")
print(f"stubs.cpp: {len(labels)} weak stand-ins for retail labels")
